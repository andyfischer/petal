    /// Compile `src`, then lower it twice — without the pass and with it. The
    /// `Env` is returned alongside because it owns the `Program` the lowerings
    /// (and the origin-term assertions) borrow.
    fn lowered(src: &str) -> (BytecodeProgram, BytecodeProgram, Env) {
        let mut env = Env::new();
        let pid = env.load_program(src).expect("compiles");
        let program = env.get_program(pid).expect("program");
        let plain = super::super::lower_program(program).expect("lowers");
        let mut opt = super::super::lower_program(program).expect("lowers");
        apply(&mut opt, program, OBSERVED);
        (plain, opt, env)
    }

    fn count(bc: &BytecodeProgram, op: Opcode) -> usize {
        std::iter::once(&bc.root)
            .chain(bc.fns.iter())
            .flat_map(|f| f.code.iter())
            .filter(|i| i.opcode() == op)
            .count()
    }

    /// Run `src` with the pass off and on, assert the two agree, and return the
    /// output. Equality with the unoptimized lowering is the property that
    /// matters — an absolute expectation would only restate the language's
    /// semantics, which are tested elsewhere.
    fn run_both(src: &str) -> String {
        let go = |flags: crate::policy::RunPolicy| {
            let mut env = Env::new();
            env.set_policy(flags);
            let pid = env.load_program(src).expect("loads");
            let sid = env.create_stack(pid).expect("stack");
            let value = env.run(sid).expect("runs");
            let rendered = crate::value::value_to_display_string(&value, env.heap());
            (rendered, env.take_output().join("\n"))
        };
        let plain = go(crate::policy::RunPolicy::BASELINE);
        let opt = go(crate::policy::RunPolicy::FAST);
        assert_eq!(
            plain, opt,
            "copy propagation changed the program's behavior"
        );
        opt.1
    }

