//! The packages compiled into the petal binary.
//!
//! A bundled package is an ordinary `petal.toml` package — Petal source and
//! `native fn` declarations — whose files `core/build.rs` embeds, so they are
//! there with no filesystem (wasm) and wherever the binary is copied. The
//! build fails if a bundled package's directory is missing.
//!
//! `core` holds the declarations of the builtins every program can call
//! without an import (`core/packages/core`); they are bound in every file's
//! global scope, see [`crate::native_decl::core_decls`]. The domain builtins
//! ([`BUILTIN_PACKAGES`]: `noise`, `color`, …) are registered in every Env
//! too but are in scope only where imported. `ui` is the petal-ui interface,
//! always embedded. The rest are first-party libraries (`bloom`,
//! `text_layout`, `glsl`), each embedded only when its cargo feature of the
//! same name is on (`libraries` turns on all of them); [`LIBRARIES`] lists
//! the ones in this build and [`OMITTED_LIBRARIES`] the ones it leaves out.
//! The list of packages, their kinds and features lives in `core/Cargo.toml`
//! under [package.metadata.petal.bundled].

/// One embedded package: its name and every file it is made of.
#[derive(Debug)]
pub struct BundledPackage {
    /// The `[package] name`.
    pub name: &'static str,
    /// `(path relative to the package root, contents)`, sorted by path:
    /// `petal.toml` and each `*.ptl` under it.
    pub files: &'static [(&'static str, &'static str)],
}

impl BundledPackage {
    /// The package's `petal.toml`.
    pub fn manifest(&self) -> &'static str {
        self.files
            .iter()
            .find(|(path, _)| *path == crate::package::MANIFEST_FILE)
            .map(|(_, text)| *text)
            .unwrap_or("")
    }

    /// The package's Petal sources: `(path relative to the package root,
    /// source)` for each `*.ptl`, sorted by path.
    pub fn sources(&self) -> impl Iterator<Item = (&'static str, &'static str)> {
        self.files
            .iter()
            .copied()
            .filter(|(path, _)| path.ends_with(".ptl"))
    }
}

/// Whether the embedded Petal sources (the bundled packages, the std prelude)
/// had their whole-line comments stripped by `core/build.rs`. On by default for
/// wasm32, where every byte is downloaded; off for native builds, whose tools
/// show the comments of bundled code. `PETAL_EMBED_COMMENTS=keep|strip` at
/// build time overrides it. Lines are blanked, not removed, so positions in
/// error messages match the repository files either way.
pub const COMMENTS_STRIPPED: bool =
    matches!(env!("PETAL_EMBED_COMMENTS_STRIPPED").as_bytes(), b"1");

/// Every bundled package in this build, in the order core/Cargo.toml lists
/// them.
pub static BUNDLED_PACKAGES: &[BundledPackage] =
    include!(concat!(env!("OUT_DIR"), "/bundled_packages.rs"));

/// The bundled package called `name`.
pub fn package(name: &str) -> Option<&'static BundledPackage> {
    BUNDLED_PACKAGES.iter().find(|p| p.name == name)
}

/// The name of the package that declares the always-in-scope builtins.
pub const CORE_PACKAGE: &str = "core";

// Generated by `core/build.rs` from [package.metadata.petal.bundled] in
// core/Cargo.toml:
//
// - `BUILTIN_PACKAGES: &[&str]` — the packages (kind `builtin`) that declare
//   the *domain* builtins: natives the runtime registers in every Env
//   ([`crate::builtins::register_builtins`]), but which are in scope only in
//   a file that imports the package (`import noise`). One per group of
//   `core/src/builtins/`; `io` is the host-I/O set of `output.rs`. The
//   creative-coding set (`lerp`, `mag`, …) is declared by `core` and needs no
//   import.
// - `LIBRARIES: &[&str]` — the bundled libraries embedded in this build.
// - `OMITTED_LIBRARIES: &[(&str, &str)]` — the bundled libraries this build
//   leaves out, each with the `petal` crate feature that embeds it. An import
//   of one fails with a message naming the feature.
include!(concat!(env!("OUT_DIR"), "/bundled_meta.rs"));

/// Bundled packages that no longer exist because `core` declares their
/// builtins now: `import creative` names nothing, says so when it fails to
/// resolve, and `petal migrate-old-code` (`old-imports`) deletes it.
pub const MERGED_INTO_CORE: &[&str] = &["creative"];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn core_is_bundled_with_its_manifest_and_modules() {
        let core = package(CORE_PACKAGE).expect("core is bundled");
        assert!(core.manifest().contains("name = \"core\""));
        let modules: Vec<&str> = core.sources().map(|(path, _)| path).collect();
        assert!(modules.contains(&"src/math.ptl"), "{modules:?}");
        assert!(modules.contains(&"src/collections.ptl"), "{modules:?}");
        assert!(package("nope").is_none());
    }

    #[test]
    fn a_library_is_either_embedded_or_listed_as_omitted() {
        for name in LIBRARIES {
            assert!(package(name).is_some(), "{name}");
            assert!(OMITTED_LIBRARIES.iter().all(|(n, _)| n != name), "{name}");
        }
        for (name, feature) in OMITTED_LIBRARIES {
            assert!(package(name).is_none(), "{name}");
            assert!(!feature.is_empty(), "{name}");
        }
        for name in BUILTIN_PACKAGES {
            assert!(package(name).is_some(), "{name}");
        }
    }
}
