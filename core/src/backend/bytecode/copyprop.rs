//! Copy propagation and dead-move elimination over lowered bytecode.
//!
//! Lowering gives every IR term its own flat register, and the term graph has a
//! `Copy` term for every *use* of a variable plus a `Phi` for every rebinding —
//! so the instruction stream that comes out is roughly half `Move`. On the
//! spreadsheet benchmark, 47% of all retired instructions were moves; each one
//! is a register read, a register write, and a full trip through the dispatch
//! loop, which is the most expensive part of executing a cheap instruction.
//!
//! This pass runs after lowering (and after `lastuse`, so it cannot disturb the
//! alias groups that route A reasons about) and does two standard things:
//!
//! 1. **Copy propagation.** A forward dataflow computes, at every program
//!    point, which registers are known to hold the same value as another
//!    (`d ≡ s`, generated by `Move d <- s`, killed when either side is
//!    rewritten). Reads of `d` are rewritten to read `s`. This alone removes no
//!    instructions — it makes the moves *dead*.
//! 2. **Dead-move elimination.** A backward liveness pass finds moves whose
//!    destination is not live afterwards. Those are dropped, the code is
//!    compacted, and every branch target is remapped.
//!
//! Self-moves (`Move d <- d`, which lowering emits at some join edges) are
//! dropped whenever nothing can observe them, which is every run that is not
//! tracing.
//!
//! # What is deliberately preserved
//! Both guards live in [`Preserve`], set from [`crate::backend::OptFlags`] by
//! whichever debug facility is on.
//!
//! `Preserve::observations`: a `Move` whose origin term is **named** is kept
//! even when dead. Naming is exactly the filter the VM's observation buffer
//! applies (`Vm::is_observable`), and an embedder reads a frame's bindings out
//! of that buffer — Garden's `panel.values` and the debug server's `/state` are
//! this, and the `--observe` CLI dump is too. Deleting the instruction that
//! writes `d` would silently drop the binding from that report.
//!
//! `Preserve::trace`: every instruction carrying an origin term is kept, named
//! or not. The trace is addressed per *term* — provenance, `explain`, and
//! direct manipulation all look up `last_for_term` — so an unnamed temporary
//! does have a reader after all. Solving `x0 + i * spacing` for `spacing` needs
//! the value the loop counter `i` took, and the read of `i` is precisely an
//! unnamed dead move; without this guard the solve silently finds nothing.
//!
//! # Soundness
//! Propagation only rewrites a read of `d` to `s` at a point where every path
//! reaching it passes a `Move d <- s` with no intervening write to either
//! register — the meet is intersection over predecessors, so a fact must hold on
//! *all* paths, and any write to either side kills it. A move is deleted only
//! when its destination is dead on every path out, which is a whole-function
//! backward analysis over the same CFG (`falls_through` + `branch_target`) the
//! last-use pass uses. Registers that a frame push fills in (parameters,
//! captures, the self-reference) have no defining instruction, and the
//! function's `result_reg` is treated as live at the exit, so neither can be
//! deleted out from under the frame protocol.

use std::collections::HashMap;

use smallvec::SmallVec;

use super::isa::{BytecodeFn, BytecodeProgram, Inst, Reg};
use crate::program::{Program, TermId};

/// What one run of the pass changed, for tests and for the `PETAL_OPT_STATS`
/// dump.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct CopyPropStats {
    /// Operand reads rewritten to a propagated source register.
    pub rewritten: usize,
    /// `Move` instructions deleted.
    pub removed: usize,
    /// Branches retargeted past an intervening `Jump`, plus `Jump`s to the very
    /// next instruction that were dropped.
    pub threaded: usize,
    /// Instructions in the program before the pass.
    pub before: usize,
    /// Instructions in the program after it.
    pub after: usize,
}

/// What a run is watching, and therefore what this pass may not delete.
///
/// Both flags cost real instructions — the moves in question are the phi copies
/// of user variables, the most frequent kind — so each is set only when
/// something is actually reading the results back. See
/// [`crate::backend::OptFlags`].
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Preserve {
    /// Keep every dead-but-*named* `Move`, so a host reading a run's bindings
    /// back (`--observe`, Garden's `panel.values`) sees the same set it would
    /// without the pass.
    pub observations: bool,
    /// Keep every dead pure instruction that carries an origin term (and every
    /// self-move that does), so the trace records a value for each term. The
    /// trace is read per-term — provenance, `explain`, direct manipulation — and
    /// anonymous terms are exactly what a solve inverts against, so the narrower
    /// `observations` rule is not enough.
    pub trace: bool,
}

impl Preserve {
    /// Whether an instruction with this origin has to survive even when its
    /// destination is dead.
    fn keeps(&self, program: &Program, origin: Option<TermId>) -> bool {
        (self.trace && origin.is_some()) || (self.observations && is_observable(program, origin))
    }
}

/// Run the pass over every function of `bc`.
pub fn apply(bc: &mut BytecodeProgram, program: &Program, preserve: Preserve) -> CopyPropStats {
    let mut stats = CopyPropStats::default();
    let match_binds = std::mem::take(&mut bc.match_binds);
    apply_fn(&mut bc.root, program, &match_binds, preserve, &mut stats);
    for f in &mut bc.fns {
        apply_fn(f, program, &match_binds, preserve, &mut stats);
    }
    bc.match_binds = match_binds;
    stats
}

type Binds = HashMap<(TermId, u16), Vec<(String, Reg)>>;

/// How many propagate/eliminate rounds to run per function. Deleting a copy can
/// expose the one that fed it, so a second pass finds more than the first; the
/// third rarely finds anything, which is where the loop stops.
const PASSES: usize = 3;

fn apply_fn(
    f: &mut BytecodeFn,
    program: &Program,
    binds: &Binds,
    preserve: Preserve,
    stats: &mut CopyPropStats,
) {
    stats.before += f.code.len();
    for _ in 0..PASSES {
        if f.code.is_empty() {
            break;
        }
        stats.rewritten += propagate(f, binds);
        let removed = eliminate(f, program, binds, preserve);
        stats.removed += removed;
        if removed == 0 {
            break;
        }
    }
    stats.threaded += thread_jumps(f);
    stats.after += f.code.len();
}

// ---------------------------------------------------------------------------
// CFG
// ---------------------------------------------------------------------------
//
// Both analyses below are solved per basic block over bit sets, and only then
// replayed instruction by instruction inside each block. Solving them per
// instruction over hash maps (as this pass first did; `reference` in the tests
// keeps that formulation as the oracle) costs time quadratic in the length of
// a function, because straight-line code accumulates a fact per `Move` and
// every instruction copied and filtered the whole set. A program's top level
// is one function, tens of thousands of instructions long in a large script,
// and this pass was most of the time a hot reload took.

/// Successor instruction indices of `j`. `code.len()` is the exit pseudo-node
/// (running off the end of the function), which is also where an out-of-range
/// branch target lands.
fn succs(code: &[Inst], j: usize) -> SmallVec<[usize; 2]> {
    let exit = code.len();
    let mut out = SmallVec::new();
    if code[j].falls_through() {
        out.push((j + 1).min(exit));
    }
    if let Some(to) = code[j].branch_target() {
        out.push((to as usize).min(exit));
    }
    out
}

/// The basic blocks of a function: maximal runs of instructions entered only
/// at the top and left only at the bottom.
struct Blocks {
    /// First instruction of each block, plus `code.len()` as a sentinel, so
    /// block `b` is `starts[b]..starts[b + 1]`.
    starts: Vec<usize>,
    /// Successor blocks of each block; `EXIT` for running off the end.
    succs: Vec<SmallVec<[usize; 2]>>,
    /// Predecessor blocks of each block.
    preds: Vec<Vec<usize>>,
}

/// The exit pseudo-block.
const EXIT: usize = usize::MAX;

impl Blocks {
    fn new(code: &[Inst]) -> Blocks {
        let n = code.len();
        let mut leader = vec![false; n + 1];
        leader[0] = true;
        for (j, inst) in code.iter().enumerate() {
            let target = inst.branch_target();
            if let Some(to) = target {
                leader[(to as usize).min(n)] = true;
            }
            if target.is_some() || !inst.falls_through() {
                leader[j + 1] = true;
            }
        }
        let mut starts: Vec<usize> = (0..n).filter(|&j| leader[j]).collect();
        let mut block_of = vec![0usize; n];
        for (b, &start) in starts.iter().enumerate() {
            let end = starts.get(b + 1).copied().unwrap_or(n);
            block_of[start..end].fill(b);
        }
        let count = starts.len();
        starts.push(n);
        let mut succ_blocks: Vec<SmallVec<[usize; 2]>> = Vec::with_capacity(count);
        let mut preds = vec![Vec::new(); count];
        for b in 0..count {
            let last = starts[b + 1] - 1;
            let mut out: SmallVec<[usize; 2]> = SmallVec::new();
            for s in succs(code, last) {
                let sb = if s >= n { EXIT } else { block_of[s] };
                if !out.contains(&sb) {
                    out.push(sb);
                }
                if sb != EXIT {
                    preds[sb].push(b);
                }
            }
            succ_blocks.push(out);
        }
        Blocks {
            starts,
            succs: succ_blocks,
            preds,
        }
    }

    fn len(&self) -> usize {
        self.succs.len()
    }

    fn range(&self, b: usize) -> std::ops::Range<usize> {
        self.starts[b]..self.starts[b + 1]
    }
}

/// A fixed-size bit set.
#[derive(Clone, PartialEq, Eq)]
struct Bits(Vec<u64>);

impl Bits {
    fn new(len: usize) -> Bits {
        Bits(vec![0; len.div_ceil(64)])
    }
    #[inline]
    fn set(&mut self, i: usize) {
        self.0[i / 64] |= 1 << (i % 64);
    }
    #[inline]
    fn clear(&mut self, i: usize) {
        self.0[i / 64] &= !(1 << (i % 64));
    }
    #[inline]
    fn test(&self, i: usize) -> bool {
        self.0[i / 64] & (1 << (i % 64)) != 0
    }
    fn zero(&mut self) {
        self.0.fill(0);
    }
    fn ones(&self) -> impl Iterator<Item = usize> + '_ {
        self.0.iter().enumerate().flat_map(|(w, &word)| {
            let mut word = word;
            std::iter::from_fn(move || {
                if word == 0 {
                    return None;
                }
                let bit = word.trailing_zeros() as usize;
                word &= word - 1;
                Some(w * 64 + bit)
            })
        })
    }
}

/// One past the highest register the function mentions.
fn reg_space(f: &mut BytecodeFn, binds: &Binds) -> usize {
    let mut top = f.reg_count as usize;
    let mut see = |r: Reg| top = top.max(r as usize + 1);
    for inst in f.code.iter_mut() {
        inst.for_each_write(binds, &mut see);
        inst.for_each_read_mut(|r| see(*r));
    }
    if let Some(r) = f.result_reg {
        see(r);
    }
    top
}

// ---------------------------------------------------------------------------
// 1. Copy propagation
// ---------------------------------------------------------------------------

/// "No copy": the value of [`propagate`]'s `d -> s` table for a register that
/// is not currently known to equal another.
const NO_COPY: u32 = u32::MAX;

/// How many sweeps the block-level fixpoints may take. Each converges in about
/// as many sweeps as loops are nested; the bound exists so a pathological CFG
/// degrades to "optimize nothing" rather than to a hang.
const MAX_SWEEPS: usize = 4096;

/// Rewrite operand reads to their propagated sources. Returns how many reads
/// were rewritten.
///
/// The facts are *available copies*: `d ≡ s` holds at a point when every path
/// to it passes a `Move d <- s` with no later write to either register. Each
/// distinct `(d, s)` pair a `Move` establishes is one bit; a block's effect on
/// the set is a kill mask (every pair mentioning a register it writes) and a
/// gen mask (the pairs still standing at its end), and the meet over
/// predecessors is intersection.
fn propagate(f: &mut BytecodeFn, binds: &Binds) -> usize {
    // The distinct copies the function can establish.
    let mut pair_ids: HashMap<(Reg, Reg), u32> = HashMap::new();
    let mut pairs: Vec<(Reg, Reg)> = Vec::new();
    for inst in &f.code {
        if let Inst::Move { dst, src } = *inst
            && dst != src
        {
            pair_ids.entry((dst, src)).or_insert_with(|| {
                pairs.push((dst, src));
                pairs.len() as u32 - 1
            });
        }
    }
    if pairs.is_empty() {
        return 0;
    }
    let regs = reg_space(f, binds);
    // The pairs each register takes part in: what a write to it kills.
    let mut mentions: Vec<Vec<u32>> = vec![Vec::new(); regs];
    for (id, &(d, s)) in pairs.iter().enumerate() {
        mentions[d as usize].push(id as u32);
        mentions[s as usize].push(id as u32);
    }

    let blocks = Blocks::new(&f.code);
    let count = blocks.len();
    let mut kill: Vec<Bits> = Vec::with_capacity(count);
    let mut generate: Vec<Bits> = Vec::with_capacity(count);
    for b in 0..count {
        let (mut k, mut g) = (Bits::new(pairs.len()), Bits::new(pairs.len()));
        for inst in &f.code[blocks.range(b)] {
            inst.for_each_write(binds, |w| {
                for &id in &mentions[w as usize] {
                    k.set(id as usize);
                    g.clear(id as usize);
                }
            });
            if let Inst::Move { dst, src } = *inst
                && dst != src
            {
                g.set(pair_ids[&(dst, src)] as usize);
            }
        }
        kill.push(k);
        generate.push(g);
    }

    // Forward fixpoint. `None` is a block no reached path enters yet; the
    // entry starts with nothing known. Facts only shrink once a block has
    // been reached, so this is the greatest fixpoint whatever the order.
    let mut entry: Vec<Option<Bits>> = vec![None; count];
    let mut exit: Vec<Option<Bits>> = vec![None; count];
    let mut changed = true;
    let mut sweeps = 0;
    while changed {
        sweeps += 1;
        if sweeps > MAX_SWEEPS {
            return 0;
        }
        changed = false;
        for b in 0..count {
            let mut acc: Option<Bits> = (b == 0).then(|| Bits::new(pairs.len()));
            for &p in &blocks.preds[b] {
                let Some(out) = &exit[p] else { continue };
                match &mut acc {
                    None => acc = Some(out.clone()),
                    Some(a) => {
                        for (x, y) in a.0.iter_mut().zip(&out.0) {
                            *x &= *y;
                        }
                    }
                }
            }
            let Some(acc) = acc else { continue };
            if entry[b].as_ref() == Some(&acc) {
                continue;
            }
            let mut out = acc.clone();
            for ((x, k), g) in out.0.iter_mut().zip(&kill[b].0).zip(&generate[b].0) {
                *x = (*x & !*k) | *g;
            }
            entry[b] = Some(acc);
            exit[b] = Some(out);
            changed = true;
        }
    }

    // Replay each block from its entry facts, rewriting as it goes. `copy_of`
    // is the current facts as a `d -> s` table (at most one copy per `d`
    // stands at a time: establishing one kills every other pair mentioning
    // `d`).
    let mut rewritten = 0;
    let mut copy_of: Vec<u32> = vec![NO_COPY; regs];
    for b in 0..count {
        let Some(facts) = &entry[b] else { continue };
        let mut live = facts.clone();
        let mut standing = 0usize;
        for id in live.ones() {
            let (d, s) = pairs[id];
            copy_of[d as usize] = s as u32;
            standing += 1;
        }
        for j in blocks.range(b) {
            // The copy this instruction establishes, read before its source
            // operand is rewritten: the facts describe the code as it was.
            let own = match f.code[j] {
                Inst::Move { dst, src } if dst != src => Some((dst, src)),
                _ => None,
            };
            if standing > 0 {
                // Every read — including a `Move`'s own source — follows the
                // fact chain to its root, so a chain of copies collapses to
                // reads of one register in a single pass and the intermediate
                // links fall out as dead.
                f.code[j].for_each_read_mut(|r| {
                    if let Some(root) = resolve(&copy_of, *r) {
                        if root != *r {
                            *r = root;
                            rewritten += 1;
                        }
                    }
                });
            }
            f.code[j].for_each_write(binds, |w| {
                for &id in &mentions[w as usize] {
                    if live.test(id as usize) {
                        live.clear(id as usize);
                        copy_of[pairs[id as usize].0 as usize] = NO_COPY;
                        standing -= 1;
                    }
                }
            });
            if let Some((d, s)) = own {
                live.set(pair_ids[&(d, s)] as usize);
                copy_of[d as usize] = s as u32;
                standing += 1;
            }
        }
        for id in live.ones() {
            copy_of[pairs[id].0 as usize] = NO_COPY;
        }
    }
    rewritten
}

/// Follow `d ≡ s` links to the end of the chain. Cycles cannot arise (a fact is
/// killed when its destination is rewritten) but the hop budget makes that
/// structural rather than assumed.
fn resolve(copy_of: &[u32], mut r: Reg) -> Option<Reg> {
    let mut out = None;
    for _ in 0..8 {
        match copy_of[r as usize] {
            NO_COPY => break,
            s if s as Reg != r => {
                r = s as Reg;
                out = Some(r);
            }
            _ => break,
        }
    }
    out
}

