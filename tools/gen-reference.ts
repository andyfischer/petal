// ── The model: what a reference page lists ───────────────────────────────────

export interface Section {
  /** The heading: a module name (`ui/draw`, `std`). */
  name: string;
  doc: Doc | null;
  /** Repo-relative file of the module, for the source link. */
  file: string;
  note?: string;
  /** The package root module (`ui`, `core`): its doc is the package's. */
  root?: boolean;
  items: Array<{ item: DocItem; file: string; from?: string }>;
}

/** The last path segment starts with `_`: a module the package keeps to itself. */
const isInternalModule = (name: string) => /(^|\/)_[^/]*$/.test(name);

/** Hidden, or a `__`-prefixed internal name. */
const isHiddenItem = (item: DocItem) => item.hidden || item.name.startsWith("__");

/**
 * The sections one `petal doc` report contributes, one per public module in
 * module order. An item of an internal module (`ui/_base`) is listed under the
 * first public module that re-exports it (preferring a submodule over the
 * root), and left out when none does. The package's root module gets a
 * section only when it declares items of its own; its doc is the page's.
 */
export function sectionsOf(report: DocReport, source: Source): Section[] {
  const rootName = report.package?.root_module ?? null;
  const byName = new Map<string, Section>();
  const sections: Section[] = [];
  for (const mod of report.modules) {
    if (isInternalModule(mod.name) || mod.doc?.hidden) continue;
    const section: Section = {
      name: source.name ?? mod.name,
      doc: mod.doc,
      file: moduleFile(report, mod),
      items: [],
      ...(mod.name === rootName ? { root: true } : {}),
    };
    byName.set(mod.name, section);
    sections.push(section);
  }
  const reexporter = (mod: DocModule, item: DocItem): Section | undefined => {
    const candidates = report.modules.filter(
      (m) =>
        byName.has(m.name) &&
        m.reexports.some(
          (r) => r.canonical === mod.name && (r.names === null || r.names.includes(item.name)),
        ),
    );
    const pick = candidates.find((m) => m.name !== rootName) ?? candidates[0];
    return pick ? byName.get(pick.name) : undefined;
  };
  for (const mod of report.modules) {
    for (const item of mod.items) {
      if (!item.exported || isHiddenItem(item)) continue;
      const file = moduleFile(report, mod);
      if (byName.has(mod.name)) {
        byName.get(mod.name)!.items.push({ item, file });
      } else if (isInternalModule(mod.name)) {
        reexporter(mod, item)?.items.push({ item, file, from: mod.name });
      }
    }
  }
  return sections.filter(
    (s) => s.items.length > 0 || (s.name !== rootName && s.doc !== null) || report.package === null,
  );
}

// ── Markdown ─────────────────────────────────────────────────────────────────

/** GitHub's heading anchor for `text`. */
export function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .trim()
    .replace(/\s/g, "-");
}

class Anchors {
  private seen = new Map<string, number>();
  take(heading: string): string {
    const base = slug(heading);
    const n = this.seen.get(base) ?? 0;
    this.seen.set(base, n + 1);
    return n === 0 ? base : `${base}-${n}`;
  }
}

function paramText(p: DocParam, native: boolean): string {
  if (p.rest) return `...${p.name}${p.type ? `: ${p.type}` : ""}`;
  const q = p.optional && p.default === undefined && native ? "?" : "";
  return `${p.name}${q}${p.type ? `: ${p.type}` : ""}${p.default !== undefined ? ` = ${p.default}` : ""}`;
}

/** One call form as Petal: `clamp(value: num, lo: num, hi: num) -> num`. */
export function formSignature(name: string, form: DocForm): string {
  const params = form.params.map((p) => paramText(p, form.native)).join(", ");
  return `${name}(${params})${form.returns ? ` -> ${form.returns}` : ""}`;
}

/** Every way to write the item, one per line. */
export function signatures(item: DocItem): string[] {
  switch (item.kind) {
    case "fn":
    case "native_fn":
      return (item.forms ?? []).map((f) => formSignature(item.name, f));
    case "class": {
      const fields = (item.fields ?? []).map((f) => (f.type ? `${f.name}: ${f.type}` : f.name));
      return [`class ${item.name}(${fields.join(", ")})`];
    }
    case "enum": {
      const variants = (item.variants ?? []).map((v) =>
        v.fields.length ? `${v.name}(${v.fields.join(", ")})` : v.data.length ? `${v.name}(${v.data.map((d) => `${d}: …`).join(", ")})` : v.name,
      );
      return [`enum ${item.name} { ${variants.join(", ")} }`];
    }
    default: {
      const kw = item.kind === "state_var" ? "state var" : item.kind;
      return [`${kw} ${item.name}${item.type ? `: ${item.type}` : ""}${item.value ? ` = ${item.value}` : ""}`];
    }
  }
}

/** A table cell: one line, pipes escaped. */
const cell = (text: string) => text.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");

/** The parameters a doc's `params:` names, with each one's declared type. */
function paramTypes(item: DocItem): Map<string, string | null> {
  const out = new Map<string, string | null>();
  for (const form of item.forms ?? []) {
    for (const p of form.params) if (!out.has(p.name) || out.get(p.name) === null) out.set(p.name, p.type);
  }
  return out;
}

interface Linker {
  /** A Markdown link for a `see:` entry, or the entry in code when nothing on the page matches. */
  see(name: string): string;
}

function renderDocFields(doc: Doc, item: DocItem | null, link: Linker, out: string[]) {
  if (doc.deprecated) out.push(`**Deprecated:** ${doc.deprecated}`, "");
  if (doc.body) out.push(doc.body, "");
  const params = Object.entries(doc.params);
  if (params.length) {
    const types = item ? paramTypes(item) : new Map();
    out.push("**Parameters**", "");
    for (const [name, text] of params) {
      const type = types.get(name);
      out.push(`- \`${name}\`${type ? ` (\`${type}\`)` : ""}: ${text.replace(/\n/g, "\n  ")}`);
    }
    out.push("");
  }
  const options = Object.entries(doc.options);
  if (options.length) {
    out.push("**Options**", "", "| Key | Meaning |", "|---|---|");
    for (const [key, text] of options) out.push(`| \`${key}\` | ${cell(text)} |`);
    out.push("");
  }
  if (doc.returns) out.push(`**Returns** ${doc.returns}`, "");
  if (doc.example.length) {
    out.push(doc.example.length > 1 ? "**Examples**" : "**Example**", "");
    for (const ex of doc.example) out.push("```petal", ex, "```", "");
  }
  if (doc.see.length) out.push(`**See also:** ${doc.see.map((s) => link.see(s)).join(", ")}`, "");
}

/** A link from the output file to `file` at `line`. */
function sourceLink(outPath: string, file: string, line?: number): string {
  if (file.startsWith("<")) return `\`${file}\``;
  const rel = relative(dirname(outPath), file);
  return `[\`${file}${line ? `:${line}` : ""}\`](${rel}${line ? `#L${line}` : ""})`;
}

/**
 * The groups a module doc names in `extra.groups`, a list of
 * `{name, items, doc?}`: subheadings for a long module, each with an
 * optional intro (Markdown, any common indent removed).
 */
export function docGroups(doc: Doc | null): Array<{ name: string; items: string[]; doc: string | null }> {
  const raw = doc?.extra?.groups;
  if (!Array.isArray(raw)) return [];
  return raw
    .filter((g): g is Record<string, unknown> => !!g && typeof g === "object" && typeof (g as any).name === "string")
    .map((g) => ({
      name: g.name as string,
      items: Array.isArray(g.items) ? g.items.filter((n): n is string => typeof n === "string") : [],
      doc: typeof g.doc === "string" && g.doc.trim() ? dedent(g.doc) : null,
    }));
}

function dedent(text: string): string {
  const lines = text.replace(/^\s*\n/, "").trimEnd().split("\n");
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)![0].length));
  return lines.map((l) => l.slice(indent)).join("\n");
}

type Entry = Section["items"][number];

/**
 * A section's items under the groups its module doc names, in the groups'
 * order; items no group names follow under "Other". `null` when the module
 * names no groups (the items stay flat, in source order).
 */
export function groupSection(s: Section): Array<{ name: string; doc: string | null; items: Entry[] }> | null {
  const groups = docGroups(s.doc);
  if (!groups.length) return null;
  const byName = new Map(s.items.map((e) => [e.item.name, e]));
  const placed = new Set<string>();
  const out = groups.map((g) => {
    const items: Entry[] = [];
    for (const n of g.items) {
      const e = byName.get(n);
      if (!e) process.stderr.write(`gen-reference: ${s.name}: group "${g.name}" names ${n}, which the section does not list\n`);
      else if (!placed.has(n)) (placed.add(n), items.push(e));
    }
    return { name: g.name, doc: g.doc, items };
  });
  const rest = s.items.filter((e) => !placed.has(e.item.name));
  if (rest.length) out.push({ name: "Other", doc: null, items: rest });
  return out.filter((g) => g.items.length);
}

/** `sections` in `order` (see `Target.moduleOrder`); the sort is stable. */
export function orderSections<S extends { name: string }>(sections: S[], order?: string[]): S[] {
  if (!order?.length) return sections;
  const rest = order.includes("*") ? order.indexOf("*") : order.length;
  const rank = (s: S) => (order.includes(s.name) ? order.indexOf(s.name) : rest);
  return [...sections].sort((a, b) => rank(a) - rank(b));
}

/** The whole reference page for `target`, given its `petal doc` reports in source order. */
export function renderTarget(target: Target, reports: DocReport[]): string {
  const unordered = target.sources.flatMap((source, i) =>
    sectionsOf(reports[i], source).map((s) => ({
      ...s,
      note: s.note ?? source.note,
      // The first package's root module doc is the page's intro: not twice.
      pageRoot: i === 0 && !!s.root && !!reports[0].package?.doc,
    })),
  );
  const sections = orderSections(unordered, target.moduleOrder);
  // Anchors in page order: the title, Contents, then each section and its items.
  const anchors = new Anchors();
  anchors.take(target.title);
  anchors.take("Contents");
  const sectionAnchor = new Map<Section, string>();
  const itemAnchor = new Map<string, string>(); // "module::name" and bare "name"
  // A section whose module doc names groups lists its items under them.
  const grouped = new Map(sections.map((s) => [s, groupSection(s)]));
  const groupAnchor = new Map<string, string>(); // "module::group"
  for (const s of sections) {
    sectionAnchor.set(s, anchors.take(`\`${s.name}\``));
    for (const g of grouped.get(s) ?? [{ name: null, items: s.items }]) {
      if (g.name !== null) groupAnchor.set(`${s.name}::${g.name}`, anchors.take(g.name));
      for (const { item } of g.items) {
        const a = anchors.take(`\`${item.name}\``);
        itemAnchor.set(`${s.name}::${item.name}`, a);
        if (!itemAnchor.has(item.name)) itemAnchor.set(item.name, a);
      }
    }
  }
  const sectionByName = new Map(sections.map((s) => [s.name, s]));
  const link: Linker = {
    see(name) {
      // `ui/drag` (a module), `ui.button` (a module's export), `lerp`, `Rect.inset`.
      const mod = sectionByName.get(name);
      if (mod) return `[\`${name}\`](#${sectionAnchor.get(mod)})`;
      const dot = name.indexOf(".");
      if (dot > 0) {
        const pkgOrMod = name.slice(0, dot);
        const rest = name.slice(dot + 1);
        const owner = sections.find((s) => s.name === pkgOrMod || s.name.split("/")[0] === pkgOrMod);
        if (owner && itemAnchor.has(rest)) return `[\`${name}\`](#${itemAnchor.get(rest)})`;
      }
      const a = itemAnchor.get(name);
      return a ? `[\`${name}\`](#${a})` : `\`${name}\``;
    },
  };

  const out: string[] = [GENERATED_MARKER, ""];
  out.push(
    `[//]: # "Sources: ${target.sources.map((s) => s.target).join(", ")}"`,
    "",
  );
  out.push(`# ${target.title}`, "");
  out.push("*Generated from the `@doc` and `@module_doc` in the sources (`npm run reference`); edit those, not this page.*", "");
  const pkg = reports[0].package;
  if (pkg?.doc) {
    renderDocFields(pkg.doc, null, link, out);
  } else {
    out.push(pkg?.description ? `${pkg.description} ${target.intro}` : target.intro, "");
  }

  out.push("## Contents", "");
  for (const s of sections) {
    const summary = s.doc?.summary ?? (s.items.length ? `${s.items.length} item${s.items.length === 1 ? "" : "s"}` : "");
    out.push(`- [\`${s.name}\`](#${sectionAnchor.get(s)})${summary ? `: ${summary}` : ""}`);
    for (const g of grouped.get(s) ?? []) out.push(`  - [${g.name}](#${groupAnchor.get(`${s.name}::${g.name}`)})`);
  }
  out.push("");

  for (const s of sections) {
    out.push(`## \`${s.name}\``, "");
    if (s.note) out.push(`*${s.note}*`, "");
    if (s.doc && !s.pageRoot) renderDocFields(s.doc, null, link, out);
    out.push(`Source: ${sourceLink(target.out, s.file)}`, "");
    const itemLinks = (entries: Entry[]) =>
      entries.map(({ item }) => `[\`${item.name}\`](#${itemAnchor.get(`${s.name}::${item.name}`)})`).join(" · ");
    const groups = grouped.get(s);
    if (groups) {
      for (const g of groups) {
        out.push(`- **[${g.name}](#${groupAnchor.get(`${s.name}::${g.name}`)}):** ${itemLinks(g.items)}`);
      }
      out.push("");
    } else if (s.items.length > 1) {
      out.push(itemLinks(s.items), "");
    }
    for (const g of groups ?? [{ name: null, doc: null, items: s.items }]) {
      if (g.name !== null) out.push(`### ${g.name}`, "");
      if (g.doc) out.push(g.doc, "");
      for (const { item, file, from } of g.items) {
        out.push(`${g.name !== null ? "####" : "###"} \`${item.name}\``, "");
        renderItem(item, link, out);
        out.push(
          `*Source: ${sourceLink(target.out, file, item.line)}${from ? ` (re-exported from \`${from}\`)` : ""}*`,
          "",
        );
      }
    }
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

function renderItem(item: DocItem, link: Linker, out: string[]) {
  const forms = item.forms ?? [];
  const documentedForms = forms.filter((f) => f.doc !== null);
  if (documentedForms.length > 1) {
    // Each documented form describes itself; an undocumented form is listed
    // with the one before it.
    let block: string[] = [];
    const flush = (doc: Doc | null) => {
      out.push("```petal", ...block, "```", "");
      if (doc) renderDocFields(doc, item, link, out);
      block = [];
    };
    let pending: Doc | null = null;
    forms.forEach((form, i) => {
      if (form.doc !== null && i > 0) flush(pending);
      if (form.doc !== null) pending = form.doc;
      block.push(formSignature(item.name, form));
    });
    flush(pending);
    return;
  }
  out.push("```petal", ...signatures(item), "```", "");
  if (item.doc) renderDocFields(item.doc, item, link, out);
  else out.push("*Undocumented.*", "");
}

// ── Coverage: what a hand-written reference has that the @docs lack ──────────

/** Lowercased words only, for comparing prose across Markdown and line wrapping. */
const normalize = (text: string) =>
  text
    .toLowerCase()
    .replace(/[`*_>#|[\]()]/g, " ")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();

function docTexts(doc: Doc | null): string[] {
  if (!doc) return [];
  return [
    doc.body ?? "",
    ...Object.values(doc.params),
    ...Object.values(doc.options),
    doc.returns ?? "",
    ...doc.example,
    doc.deprecated ?? "",
    ...docGroups(doc).map((g) => g.doc ?? ""),
  ];
}

export interface Coverage {
  /** Names the file documents (`` `name(`` in it) that are public items with no doc. */
  undocumented: string[];
  /** Paragraphs and code blocks of the file that appear in no doc, with their line. */
  missing: Array<{ line: number; text: string }>;
  paragraphs: number;
}

/**
 * Compare a hand-written reference with the docs of its sources. A paragraph
 * (or code block) counts as carried over when its words appear, in order, in
 * some doc's text; a name the file documents counts when its item has a doc.
 */
export function coverage(markdown: string, reports: DocReport[]): Coverage {
  const items = new Map<string, DocItem>();
  const texts: string[] = [];
  for (const report of reports) {
    texts.push(...docTexts(report.package?.doc ?? null));
    for (const mod of report.modules) {
      texts.push(...docTexts(mod.doc));
      for (const item of mod.items) {
        if (item.exported && !items.has(item.name)) items.set(item.name, item);
        texts.push(...docTexts(item.doc));
        for (const form of item.forms ?? []) texts.push(...docTexts(form.doc));
      }
    }
  }
  const corpus = texts.map(normalize).join(" \u0000 ");
  const documented = (item: DocItem) => item.doc !== null || (item.forms ?? []).some((f) => f.doc !== null);
  const named = new Set([...markdown.matchAll(/`([A-Za-z_][\w.]*)\(/g)].map((m) => m[1]));
  const undocumented = [...named].filter((n) => items.has(n) && !documented(items.get(n)!)).sort();

  const missing: Coverage["missing"] = [];
  let paragraphs = 0;
  const lines = markdown.split("\n");
  let block: string[] = [];
  let start = 0;
  let inFence = false;
  const flush = () => {
    const text = block.join("\n").trim();
    block = [];
    if (!text || /^#{1,6}\s/.test(text) || /^<!--/.test(text)) return;
    paragraphs++;
    const words = normalize(text);
    if (words && !corpus.includes(words)) missing.push({ line: start + 1, text });
  };
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) {
      if (inFence) {
        inFence = false;
        flush();
      } else {
        flush();
        inFence = true;
        start = i + 1;
      }
      return;
    }
    if (inFence) {
      block.push(line);
      return;
    }
    if (line.trim() === "" || /^#{1,6}\s/.test(line)) {
      flush();
      start = i + 1;
      return;
    }
    if (block.length === 0) start = i;
    block.push(line);
  });
  flush();
  return { undocumented, missing, paragraphs };
}

