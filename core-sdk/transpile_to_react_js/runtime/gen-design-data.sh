#!/bin/bash
# Regenerate petal-design-data.js: the data tables of Mixit's `design`
# package (device sizes and safe areas, type ramps), transpiled from its
# Petal source by petal-to-react itself.
#
#   runtime/gen-design-data.sh [path/to/mixit/gui/packages/design]
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
pkg="${1:-$HOME/mixit/gui/packages/design}"
bin="$here/../../../core/target/debug/petal-to-react"
(cd "$here/.." && cargo build -q --bin petal-to-react)
{
  echo "// petal-design-data.js — the data tables of Mixit's \`design\` package."
  echo "//"
  echo "// GENERATED by runtime/gen-design-data.sh from $(basename "$(dirname "$(dirname "$pkg")")")/gui/packages/design"
  echo "// (devices.ptl, type.ptl) with petal-to-react. Do not edit by hand."
  for f in devices type; do
    echo
    echo "// ── $f.ptl ──"
    # Only the top-level constants (and the comments above them).
    "$bin" "$pkg/$f.ptl" --dialect generic 2>/dev/null | awk '
      /^\/\/ (Generated|Regenerate)/ { next }
      /^import / { next }
      /^export const / { keep = 1 }
      /^\/\// && !keep { buf = buf $0 "\n"; next }
      /^$/ && !keep { buf = ""; next }
      keep { printf "%s", buf; buf = ""; print; if ($0 ~ /^[}\]];$/ || $0 ~ /;$/ && $0 !~ /[{\[]$/) { keep = 0; print "" } next }
      { buf = "" }
    '
  done
} > "$here/petal-design-data.js"
echo "wrote $here/petal-design-data.js"
